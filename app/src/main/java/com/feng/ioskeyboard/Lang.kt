    /** pref ui_lang: -1 ikut sistem, 0 Indonesia, 1 English */
    fun load(c: Context) {
        val p = c.getSharedPreferences("kb", Context.MODE_PRIVATE).getInt("ui_lang", -1)
        en = when (p) {
            0 -> false
            1 -> true
            else -> { val l = Locale.getDefault().language; !(l == "in" || l == "id") }
        }
    }

    fun set(c: Context, v: Int) {
        c.getSharedPreferences("kb", Context.MODE_PRIVATE).edit().putInt("ui_lang", v).apply()
        load(c)
    }

